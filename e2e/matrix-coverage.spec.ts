import { test, expect } from '@playwright/test';
import { resolveMicroActivity } from '../src/features/onboarding/data/activities';
import { type AcademicStageId } from '../src/data/landing-demo';
import * as fs from 'fs';
import * as path from 'path';

const STAGES: AcademicStageId[] = [
  'classes-4-7',
  'classes-8-10',
  'classes-11-12',
  'diploma',
  'degree-engineering',
  'final-year-grad',
];

const INTERESTS = [
  { id: 'technology', label: 'Technology & Software' },
  { id: 'creativity', label: 'Creativity & Media' },
  { id: 'science_discovery', label: 'Science & Discovery' },
  { id: 'business_entrepreneurship', label: 'Business & Ventures' },
  { id: 'social_impact', label: 'Social Impact & People' },
  { id: 'analysis_problem_solving', label: 'Analysis & Logic' },
  { id: 'still_exploring', label: 'Still Exploring' },
];

test.describe('Machine-Generated Stage × Interest Coverage Matrix (42 Combinations)', () => {

  test('MATRIX.1: Execute and assert all 42 Stage × Interest combinations', async () => {
    const results: Array<{
      stageId: string;
      interestId: string;
      interestLabel: string;
      activityId: string;
      activityTitle: string;
      activityType: string;
      optionsCount: number;
      hasCorrectOption: boolean;
      demonstratedCompetency: string;
    }> = [];

    let executedCount = 0;

    for (const stageId of STAGES) {
      for (const interest of INTERESTS) {
        executedCount++;
        // Execute the actual resolution logic
        const activity = resolveMicroActivity(stageId, [interest.id]);

        // Assert activity resolution validity
        expect(activity).toBeDefined();
        expect(activity.id).toBeTruthy();
        expect(activity.title).toBeTruthy();
        expect(activity.options.length).toBeGreaterThanOrEqual(2);
        
        const hasCorrect = activity.options.some((opt) => opt.isCorrect === true);
        expect(hasCorrect).toBe(true);

        results.push({
          stageId,
          interestId: interest.id,
          interestLabel: interest.label,
          activityId: activity.id,
          activityTitle: activity.title,
          activityType: activity.type,
          optionsCount: activity.options.length,
          hasCorrectOption: hasCorrect,
          demonstratedCompetency: activity.demonstratedCompetency,
        });
      }
    }

    // Verify all 42 executed
    expect(executedCount).toBe(42);
    expect(results.length).toBe(42);

    // Generate markdown coverage table
    let md = '# Machine-Generated Stage × Interest Coverage Matrix (Flow 3)\n\n';
    md += `*Generated by Playwright E2E Test Suite on ${new Date().toISOString()}*\n\n`;
    md += `**Total Executed & Verified Combinations:** ${results.length} / 42 (100%)\n\n`;
    md += '| # | Academic Stage | Interest Category | Activity ID | Activity Title | Type | Options | Correct Answer Key | Competency Awarded |\n';
    md += '|---|---|---|---|---|---|---|---|---|\n';

    results.forEach((r, idx) => {
      md += `| ${idx + 1} | \`${r.stageId}\` | ${r.interestLabel} (\`${r.interestId}\`) | \`${r.activityId}\` | ${r.activityTitle} | \`${r.activityType}\` | ${r.optionsCount} | Validated | ${r.demonstratedCompetency} |\n`;
    });

    const outputPath = path.join(process.cwd(), 'docs', 'STAGE_INTEREST_COVERAGE_MATRIX.md');
    fs.writeFileSync(outputPath, md, 'utf8');
    console.log(`[COVERAGE MATRIX EXPORTED]: ${outputPath} (${results.length} combinations verified)`);
  });

});

